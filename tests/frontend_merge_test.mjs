import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync('frontend/app.js','utf8');
const start=source.indexOf('function mergeIncremental('),end=source.indexOf('\nasync function refresh(',start);
const merge=new Function('lookback',source.slice(start,end)+';return mergeIncremental;')('24h');
const full=JSON.parse(fs.readFileSync(process.argv[2]||'artifacts/heatmap-final.json','utf8'));
const first=full.times.length-2,prices=[...new Set(full.matrix.filter(r=>r[0]>=first).map(r=>full.prices[r[1]]))].sort((a,b)=>a-b);
const pi=new Map(prices.map((v,i)=>[v,i]));
const partial={...full,incremental:true,times:full.times.slice(first),prices,matrix:full.matrix.filter(r=>r[0]>=first).map(r=>[r[0]-first,pi.get(full.prices[r[1]]),r[2]]),candles:full.candles.slice(-2),clld:full.clld.slice(-2)};
const merged=merge(full,partial),cut=Date.now()-86400000;
const absolute=d=>new Map(d.matrix.filter(r=>d.times[r[0]]>=cut).map(r=>[d.times[r[0]]+'|'+d.prices[r[1]],r[2]]));
const before=absolute(full),after=absolute(merged);
assert.equal(after.size,before.size);
for(const [k,v] of before)assert.equal(after.get(k),v);
assert.ok(merged.candles.length>=partial.candles.length);
assert.ok(merged.normalization_p98>0);
const twice=merge(merged,partial);assert.equal(twice.matrix.length,merged.matrix.length);
for(const [k,v] of absolute(twice))assert.equal(after.get(k),v);
console.log(JSON.stringify({passed:true,real_points_verified:before.size,incremental_idempotence:true,price_reindexing:true}));
